"""Build responsive help story data and artwork from design/ sources."""
from __future__ import annotations

from datetime import date
import hashlib
import json
from pathlib import Path


def outputs(root: Path):
    source = root / 'design/doc-storyboards.json'
    stories = json.loads(source.read_text())['stories']
    artwork_path = root / 'design/doc-illustrations/manifest.json'
    artwork = json.loads(artwork_path.read_text())['assets']
    generated = {}
    imports, data, assets = [], {}, {}

    def image_import(file):
        identifier = f'asset{len(imports)}'
        imports.append(f"import {identifier} from '../../assets/{file}?url'")
        return identifier

    for story_id, story in stories.items():
        if len(story['frames']) != 3:
            raise ValueError(f'{story_id}: expected three storyboard frames')
        data[story_id] = {key: value for key, value in story.items() if key != 'illustration'}
        if 'illustration' in story:
            illustration = dict(story['illustration'])
            for key, src_key in [('file', 'src'), ('mobileFile', 'mobileSrc')]:
                file = illustration.pop(key)
                name = Path(file).name
                if file != f'illustrations/{name}' or not name.endswith('.webp'):
                    raise ValueError(f'{story_id}: unexpected illustration path {file}')
                record = artwork[Path(name).stem]
                master = root / 'design/doc-illustrations' / name
                content = master.read_bytes()
                if hashlib.sha256(content).hexdigest() != record['sha256']:
                    raise ValueError(f'{master}: illustration differs from its generation record')
                generated[f'docs/assets/{file}'] = content
                illustration[src_key] = image_import(file)
                assets[file] = (story_id, story['illustration']['alt'], master.relative_to(root).as_posix())
            data[story_id]['illustration'] = illustration
    # Emit real Vite imports, while keeping the remaining content ordinary JSON.
    module = json.dumps(data, ensure_ascii=False, indent=2)
    for index in range(len(imports)):
        for key in ('src', 'mobileSrc'):
            module = module.replace(f'"{key}": "asset{index}"', f'"{key}": asset{index}')
    generated['docs/.vitepress/theme/storyboards.mjs'] = (
        '// Generated by scripts/build_design.py; edit design/doc-storyboards.json.\n'
        + '\n'.join(imports) + '\n\nexport const storyboards = ' + module + '\n')
    manifest_path = root / 'docs/assets/manifest.json'
    manifest = json.loads(manifest_path.read_text())
    # Retire only outputs owned by this generator when a story changes presentation.
    previous = {entry['file']: entry for entry in manifest['assets']
                if entry['file'] in assets or 'scripts/design_doc_storyboards.py' not in entry.get('source_files', [])}
    source_hash = hashlib.sha256(source.read_bytes() + Path(__file__).read_bytes()).hexdigest()
    for file, (story_id, description, master) in assets.items():
        output = generated[f'docs/assets/{file}']
        content = output.encode() if isinstance(output, str) else output
        digest = hashlib.sha256(content).hexdigest()
        old = previous.get(file, {})
        unchanged = old.get('sha256') == digest and old.get('source_sha256') == source_hash
        entry = {
            'file': file,
            'page': 'user-guide/playback-controls.md' if story_id == 'casting' else f'user-guide/{story_id}.md',
            'scene': description, 'bytes': len(content), 'sha256': digest,
            'source': 'AI 原创设备插图；无真实界面或设备，文字由网页排版',
            'recording_script': 'scripts/build_design.py',
            'source_files': ['design/doc-storyboards.json', 'scripts/design_doc_storyboards.py'],
            'source_sha256': source_hash,
            'generated_at': old['generated_at'] if unchanged else date.today().isoformat(),
        }
        if master:
            entry['source_files'].extend(['design/doc-illustrations/manifest.json', master])
        previous[file] = entry
    # Preserve unrelated capture records and their actual historical dates.
    files = [entry['file'] for entry in manifest['assets'] if entry['file'] in previous]
    files.extend(file for file in previous if file not in files)
    manifest['assets'] = [previous[file] for file in files]
    generated['docs/assets/manifest.json'] = json.dumps(manifest, ensure_ascii=False, indent=2) + '\n'
    return generated
