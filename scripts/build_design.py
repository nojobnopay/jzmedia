FUNCTION_GLYPHS = set('★☆♥❤⟳↻✕✖✗✔✓⚠⌕⚙☰▶►◀◄⏪⏩⏸⏹⌂⇩⇧⇪🔍📂📁🎬📺🗑🖉✎♢✚＋←→↑↓')
