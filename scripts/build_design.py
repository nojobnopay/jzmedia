def brand_outputs(manifest=None):
    assets = {asset['id']: asset for asset in (manifest or read_json('assets.json'))['assets']}
    exports = []
    def add(path, asset, fmt, dimensions, density='1x', transparent=True, safe_area=None, sources=None):
        sources = sources or [asset]
        exports.append({'path': path, 'asset': asset, 'format': fmt, 'dimensions': dimensions,
                        'units': 'viewBox' if fmt in ('svg', 'android-vector') else 'px',
                        'density': density, 'transparent': transparent, 'safe_area': safe_area or '保留母版内边距',
                        'generator_version': GENERATOR_VERSION, 'master_revision': assets[asset]['revision'],
                        'source_assets': sources, 'source_revisions': {name: assets[name]['revision'] for name in sources}})
    for folder in ['frontend/public', 'docs/assets/design']:
        # Browsers may prefer SVG even on 1x displays; use the small optical master.
        add(folder + '/favicon.svg', 'brand-favicon-16', 'svg', assets['brand-favicon-16']['grid'], 'vector')
        add(folder + '/logo.svg', 'brand-wordmark', 'svg', assets['brand-wordmark']['grid'], 'vector')
        for size in [16, 32, 48]:
            add(f'{folder}/favicon-{size}x{size}.png', f'brand-favicon-{size}' if size != 48 else 'brand-mark', 'png', [size, size])
        add(folder + '/favicon.ico', 'brand-mark', 'ico', [[16, 16], [32, 32], [48, 48]], 'multi-size',
            sources=['brand-favicon-16', 'brand-favicon-32', 'brand-mark'])
    add('frontend/public/apple-touch-icon.png', 'brand-mark', 'png', [180, 180])
    add('frontend/public/icon-512.png', 'brand-mark', 'png', [512, 512])
    add('android-tv/app/src/main/res/drawable/ic_launcher.xml', 'brand-mark', 'android-vector', assets['brand-mark']['grid'], 'vector')
    add('android-tv/app/src/main/res/drawable/jz_wordmark.xml', 'brand-wordmark', 'android-vector', assets['brand-wordmark']['grid'], 'vector')
    exports[-1]['default_dp'] = [106, 32]
    add('android-tv/app/src/main/res/drawable-xhdpi/tv_banner.png', 'brand-wordmark', 'png', [320, 180], 'xhdpi (160×90dp)', False, '居中组合宽240px，四周至少40px')
    return exports


def brand_vector_outputs(exports, manifest):
    assets = {a['id']: a for a in manifest['assets']}
    outputs = {}
    for asset in assets.values():
        if asset['category'] != 'brand':
            continue
        root = ET.parse(ROOT / asset['master']).getroot()
        expected = '0 0 ' + ' '.join(map(str, asset['grid']))
        if root.attrib.get('viewBox') != expected:
            raise ValueError(f'{asset["master"]}: brand viewBox differs from declared grid')
        for node in root:
            if node.tag != NS + 'path' or set(node.attrib) - {'d', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'fill-rule'}:
                raise ValueError(f'{asset["master"]}: brand master must contain portable outline paths')
    for spec in exports:
        if spec['format'] == 'svg':
            outputs[spec['path']] = (ROOT / assets[spec['asset']]['master']).read_bytes()
        elif spec['format'] == 'android-vector':
            root = ET.parse(ROOT / assets[spec['asset']]['master']).getroot()
            content = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build_design.py. -->\n'
            width, height = spec['dimensions']
            default_width, default_height = spec.get('default_dp', [width, height])
            content += f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{default_width}dp" android:height="{default_height}dp" android:viewportWidth="{width}" android:viewportHeight="{height}">\n'
            mapping = {'d': 'pathData', 'fill': 'fillColor', 'stroke': 'strokeColor',
                       'stroke-width': 'strokeWidth', 'stroke-linecap': 'strokeLineCap', 'stroke-linejoin': 'strokeLineJoin', 'fill-rule': 'fillType'}
            for path in root:
                attrs = []
                for key, value in path.attrib.items():
                    if key in mapping:
                        if value == 'none': value = '#00000000'
                        if key == 'fill-rule': value = 'evenOdd' if value == 'evenodd' else 'nonZero'
                        attrs.append(f'android:{mapping[key]}="{value}"')
                content += '    <path ' + ' '.join(attrs) + ' />\n'
            outputs[spec['path']] = content + '</vector>\n'
    return outputs


def render_brand(exports, manifest):
    import cairosvg
    from PIL import Image
    assets = {a['id']: a for a in manifest['assets']}
    outputs = {}
    cache = {}
    def png(asset_id, width, height):
        key = (asset_id, width, height)
        if key not in cache:
            cache[key] = cairosvg.svg2png(url=str(ROOT / assets[asset_id]['master']), output_width=width, output_height=height)
        return cache[key]
    for spec in exports:
        if spec['format'] == 'png':
            width, height = spec['dimensions']
            if spec['path'].endswith('tv_banner.png'):
                mark = Image.open(io.BytesIO(png('brand-wordmark', 240, 72))).convert('RGBA')
                canvas = Image.new('RGBA', (width, height), '#141414')
                canvas.alpha_composite(mark, ((width - mark.width) // 2, (height - mark.height) // 2))
                buf = io.BytesIO(); canvas.convert('RGB').save(buf, format='PNG'); content = buf.getvalue()
            else:
                content = png(spec['asset'], width, height)
            outputs[spec['path']] = content
        elif spec['format'] == 'ico':
            # Explicit frames preserve each optical master; Pillow's 32px source cannot invent a 48px frame.
            frames = [png('brand-favicon-16', 16, 16), png('brand-favicon-32', 32, 32), png('brand-mark', 48, 48)]
            offset = 6 + len(frames) * 16
            entries = []
            for size, frame in zip((16, 32, 48), frames):
                entries.append(struct.pack('<BBBBHHII', size, size, 0, 0, 1, 32, len(frame), offset))
                offset += len(frame)
            outputs[spec['path']] = struct.pack('<HHH', 0, 1, 3) + b''.join(entries) + b''.join(frames)
    return outputs


def validate_rasters(exports):
    errors = []
    for spec in exports:
        if spec['format'] not in ('png', 'ico'): continue
        path = ROOT / spec['path']
        if not path.exists():
            errors.append(f'{spec["path"]}: missing; run with --render-brand'); continue
        data = path.read_bytes()
        if spec['format'] == 'png':
            dims = list(struct.unpack('>II', data[16:24])) if data[:8] == b'\x89PNG\r\n\x1a\n' else None
            if dims != spec['dimensions']: errors.append(f'{spec["path"]}: wrong PNG dimensions {dims}')
        else:
            if len(data) < 6 or struct.unpack('<HH', data[:4]) != (0, 1):
                errors.append(f'{spec["path"]}: invalid ICO'); continue
            count = struct.unpack('<H', data[4:6])[0]
            dimensions = []
            for i in range(count):
                w,h,_,_,_,_,size,offset = struct.unpack('<BBBBHHII', data[6+i*16:22+i*16])
                w,h = w or 256,h or 256
                frame = data[offset:offset+size]
                actual = tuple(struct.unpack('>II',frame[16:24])) if frame[:8] == b'\x89PNG\r\n\x1a\n' else None
                if actual != (w,h): errors.append(f'{spec["path"]}: ICO entry differs from actual pixel layer')
                dimensions.append([w,h])
            if dimensions != spec['dimensions']: errors.append(f'{spec["path"]}: incomplete ICO sizes {dimensions}')
    return errors


